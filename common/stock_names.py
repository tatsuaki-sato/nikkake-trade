def get_company_name(ticker: str) -> str:
    """
    銘柄コード（例: 7203 または 7203.T）から日本企業名を取得
    """
    code = ticker.replace('.T', '').strip()
    name = STOCK_NAMES.get(code, "")
    if name:
        return f"{code} {name}"
    return code
